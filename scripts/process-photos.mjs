// Turns original photos into web-sized JPEGs for the site.
//
//   npm run photos                 # reads old_resources/website_pics/
//   npm run photos -- path/to/dir  # or any folder of .jpg/.jpeg/.png/.webp
//
// For each image it writes public/photos/<slug>-1200.jpg (gallery tiles) and
// <slug>-2048.jpg (full-screen viewer), long edge in px, then regenerates
// src/data/photos.generated.ts with every photo's size. Decoding/encoding runs
// in headless Chromium (Playwright, already a devDependency), which converts
// wide-gamut profiles to sRGB and drops all metadata, including GPS.
import { chromium } from 'playwright'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.resolve(root, process.argv[2] ?? 'old_resources/website_pics')
const outDir = path.join(root, 'public/photos')
const dataFile = path.join(root, 'src/data/photos.generated.ts')
const SIZES = [1200, 2048]
const QUALITY = 0.82

const slugify = name =>
  name
    .replace(/\.[^.]+$/, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

const files = fs
  .readdirSync(srcDir)
  .filter(f => /\.(jpe?g|png|webp)$/i.test(f))
  .sort()
if (!files.length) {
  console.error(`No images found in ${srcDir}`)
  process.exit(1)
}
fs.mkdirSync(outDir, { recursive: true })

const browser = await chromium.launch()
const page = await browser.newPage()
// Serve the originals from a fake origin so the canvas isn't tainted.
await page.route('https://photos.local/**', route => {
  const name = decodeURIComponent(new URL(route.request().url()).pathname.slice(1))
  if (!name) return route.fulfill({ body: '<!doctype html><title>photos</title>', contentType: 'text/html' })
  return route.fulfill({ path: path.join(srcDir, name) })
})
await page.goto('https://photos.local/')

const sizes = {}
for (const file of files) {
  const slug = slugify(file)
  const results = await page.evaluate(
    async ({ url, targets, quality }) => {
      const blob = await (await fetch(url)).blob()
      const full = await createImageBitmap(blob, { imageOrientation: 'from-image' })
      const out = []
      for (const long of targets) {
        const scale = Math.min(1, long / Math.max(full.width, full.height))
        const w = Math.round(full.width * scale)
        const h = Math.round(full.height * scale)
        const bmp = await createImageBitmap(blob, {
          imageOrientation: 'from-image',
          resizeWidth: w,
          resizeHeight: h,
          resizeQuality: 'high',
        })
        const canvas = new OffscreenCanvas(w, h)
        canvas.getContext('2d').drawImage(bmp, 0, 0)
        const jpeg = await canvas.convertToBlob({ type: 'image/jpeg', quality })
        const bytes = new Uint8Array(await jpeg.arrayBuffer())
        let bin = ''
        for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000))
        out.push({ long, w, h, data: btoa(bin) })
      }
      return out
    },
    { url: `https://photos.local/${encodeURIComponent(file)}`, targets: SIZES, quality: QUALITY },
  )
  for (const r of results) {
    const target = path.join(outDir, `${slug}-${r.long}.jpg`)
    fs.writeFileSync(target, Buffer.from(r.data, 'base64'))
  }
  const small = results[0]
  sizes[slug] = { w: small.w, h: small.h }
  const kb = results.map(r => `${r.long}: ${Math.round(Buffer.byteLength(r.data, 'base64') / 1024)} KB`).join(', ')
  console.log(`${file.padEnd(28)} → ${slug}  (${kb})`)
}
await browser.close()

const body = Object.entries(sizes)
  .map(([slug, { w, h }]) => `  '${slug}': { w: ${w}, h: ${h} },`)
  .join('\n')
fs.writeFileSync(
  dataFile,
  `// Generated by scripts/process-photos.mjs — do not edit by hand.\n` +
    `// Pixel size of each /photos/<slug>-${SIZES[0]}.jpg (the -${SIZES[1]} version has the same aspect ratio).\n` +
    `export const photoSizes: Record<string, { w: number; h: number }> = {\n${body}\n}\n`,
)
console.log(`\n${files.length} photos → public/photos/, sizes → src/data/photos.generated.ts`)

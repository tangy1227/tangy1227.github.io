function ProjectMedia({ media, title }: { media: Media; title: string }) {
  if (media.type === 'youtube') return <MediaEmbed type="youtube" id={media.id} title={title} />
  const contain = media.fit === 'contain'
  return (
    <div className={`media media-static ${contain ? 'figure' : ''}`}>
      <img
        src={media.src}
        alt={media.alt}
        loading="lazy"
        className={`absolute inset-0 m-auto ${contain ? 'h-[92%] w-[94%] object-contain' : 'h-full w-full object-cover object-left-top'}`}
      />
    </div>
  )
}

function TextLink({ href, label }: Link) {
  const external = href.startsWith('http')
  return (
    <a
      href={href}
      {...(external ? { target: '_blank', rel: 'noreferrer' } : {})}
      className="group inline-flex items-center gap-2 font-display font-semibold text-xs uppercase tracking-wider"
    >
      <RollText text={label} />
      <ArrowSwap up />
    </a>
  )
}

function ProjectCard({ p, flip }: { p: Project; flip: boolean }) {
  const ref = useRef<HTMLElement>(null)
  const inView = useInView(ref, { once: true, margin: '0px 0px -15% 0px' })

  return (
    <article ref={ref} className="grid lg:grid-cols-12 gap-6 md:gap-8 lg:gap-10 items-center">
      <div className={`lg:col-span-7 ${flip ? 'lg:order-2' : ''}`}>
        <RevealImage className="rounded-[10px] overflow-hidden">
          <ProjectMedia media={p.media} title={p.title} />
        </RevealImage>
      </div>
      <div className={`lg:col-span-5 max-w-2xl ${flip ? 'lg:order-1' : ''}`}>
        <motion.p
          initial={{ opacity: 0 }}
          animate={inView ? { opacity: 1 } : undefined}
          transition={{ duration: 0.8, delay: 0.05 }}
          className="eyebrow mb-3"
        >
          {p.kicker}
        </motion.p>
        <RevealLines
          as="h3"
          className="font-display font-semibold text-2xl md:text-3xl mb-3"
          lines={[p.title]}
          delay={0.1}
        />
        <motion.p
          initial={{ opacity: 0, y: 16 }}
          animate={inView ? { opacity: 1, y: 0 } : undefined}
          transition={{ duration: 0.8, ease: EASE_OUT_EXPO, delay: 0.3 }}
          className="text-muted leading-relaxed mb-5"
        >
          {p.blurb}
        </motion.p>
        <div className="flex flex-wrap gap-2 mb-6">
          {p.tags.map((t, i) => (
            <motion.span
              key={t}
              className="tag"
              initial={{ opacity: 0, y: 10 }}
              animate={inView ? { opacity: 1, y: 0 } : undefined}
              transition={{ duration: 0.6, ease: EASE_OUT_EXPO, delay: 0.4 + i * 0.05 }}
            >
              {t}
            </motion.span>
          ))}
        </div>
        <motion.div
          initial={{ opacity: 0, y: 12 }}
          animate={inView ? { opacity: 1, y: 0 } : undefined}
          transition={{ duration: 0.7, ease: EASE_OUT_EXPO, delay: 0.55 }}
          className="flex flex-wrap gap-3"
        >
          {p.links.map(l => (
            <Button key={l.label} href={l.href} variant="outline" external={l.href.startsWith('http')}>
              {l.label}
            </Button>
          ))}
        </motion.div>
      </div>
    </article>
  )
}

